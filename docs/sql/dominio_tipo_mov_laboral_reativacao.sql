-- Sem esta linha no domínio TIPO_MOV_LABORAL a Gestão Contratual mostrava o código cru.
INSERT INTO RH_T_DOMAINS (ID, DOMINIO, VALOR, DESCRICAO, REFERENCIA, ESTADO, DATA_REGISTO, USER_REGISTO_ID, USER_REGISTO_NAME)
SELECT SEQ_DOMAINS.NEXTVAL, 'TIPO_MOV_LABORAL', 'REATIVACAO', UNISTR('Reativa\00E7\00E3o'), 'CONTRATO', 'A', SYSDATE, 1, 'local'
  FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM RH_T_DOMAINS WHERE DOMINIO = 'TIPO_MOV_LABORAL' AND VALOR = 'REATIVACAO' AND REFERENCIA = 'CONTRATO');
