-- MS-022 (reteste Missão de Serviço 1.2, 09/11/2026)
-- Tipos de documento dos anexos da Submissão e Autorização da missão.
-- Spec Missão 14/09 (Anexar Documento): RH_T_DOCUMENTO.TP_DOCUMENTO_ID com REFERENCIA = MISSAO_SERVICO,
-- "convites, agendas, etc.". Não havia nenhum tipo com essa referência; o ecrã listava os 29 de todos os
-- módulos. Depois disto o front chama GET api/v1/parametrizacao/tipo-documento/ativos?referencia=MISSAO_SERVICO.
-- Idempotente: só insere o que ainda não existe (por REFERENCIA + CODIGO).

INSERT INTO RH_T_TIPOS_DOCUMENTOS (ID, REFERENCIA, CODIGO, NOME, ESTADO, DATA_REGISTO, USER_REGISTO_ID, USER_REGISTO_NAME, UUID)
SELECT SEQ_TIPO_DOCUMENTO.NEXTVAL, 'MISSAO_SERVICO', 'DCONV', 'Convite', 'A', SYSDATE, 1, 'SYSTEM', GEN_UUID()
FROM dual WHERE NOT EXISTS (SELECT 1 FROM RH_T_TIPOS_DOCUMENTOS WHERE REFERENCIA = 'MISSAO_SERVICO' AND CODIGO = 'DCONV');

INSERT INTO RH_T_TIPOS_DOCUMENTOS (ID, REFERENCIA, CODIGO, NOME, ESTADO, DATA_REGISTO, USER_REGISTO_ID, USER_REGISTO_NAME, UUID)
SELECT SEQ_TIPO_DOCUMENTO.NEXTVAL, 'MISSAO_SERVICO', 'DAGEN', 'Agenda', 'A', SYSDATE, 1, 'SYSTEM', GEN_UUID()
FROM dual WHERE NOT EXISTS (SELECT 1 FROM RH_T_TIPOS_DOCUMENTOS WHERE REFERENCIA = 'MISSAO_SERVICO' AND CODIGO = 'DAGEN');

INSERT INTO RH_T_TIPOS_DOCUMENTOS (ID, REFERENCIA, CODIGO, NOME, ESTADO, DATA_REGISTO, USER_REGISTO_ID, USER_REGISTO_NAME, UUID)
SELECT SEQ_TIPO_DOCUMENTO.NEXTVAL, 'MISSAO_SERVICO', 'DOMS', 'Outro', 'A', SYSDATE, 1, 'SYSTEM', GEN_UUID()
FROM dual WHERE NOT EXISTS (SELECT 1 FROM RH_T_TIPOS_DOCUMENTOS WHERE REFERENCIA = 'MISSAO_SERVICO' AND CODIGO = 'DOMS');

COMMIT;
