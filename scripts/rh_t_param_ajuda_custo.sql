-- =====================================================================
-- Parametrização da Ajuda de Custo (Missão de Serviço)
--
-- Valor diário da ajuda de custo por Carreira/Cargo (RH_T_PARAM_CARREIRA), nacional e
-- estrangeiro, com período de vigência. Mesmo padrão de RH_T_PARAM_EMPRESTIMO
-- (sequência + trigger para ID/DATA_REGISTO, auditoria AuditEntity).
-- =====================================================================

CREATE SEQUENCE SEQ_PARAM_AJUDA_CUSTO START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE RH_T_PARAM_AJUDA_CUSTO (
  ID                   NUMBER        NOT NULL,
  CARR_PCCS_ID         NUMBER        NOT NULL,
  VALOR_NACIONAL       NUMBER(15,2),
  VALOR_ESTRANGEIRO    NUMBER(15,2),
  DATA_INICIO          DATE          NOT NULL,
  DATA_FIM             DATE,
  ESTADO               VARCHAR2(1)   NOT NULL,
  DATA_REGISTO         DATE          NOT NULL,
  USER_REGISTO_ID      NUMBER        NOT NULL,
  USER_REGISTO_NAME    VARCHAR2(200) NOT NULL,
  USER_ALTERACAO_ID    NUMBER,
  USER_ALTERACAO_NAME  VARCHAR2(200),
  DATA_ALTERACAO       DATE,
  UUID                 VARCHAR2(100) NOT NULL,
  CONSTRAINT PK_PARAM_AJUDA_CUSTO PRIMARY KEY (ID),
  CONSTRAINT FK_CARR_P_AJUDA_CUSTO FOREIGN KEY (CARR_PCCS_ID) REFERENCES RH_T_PARAM_CARREIRA (ID),
  CONSTRAINT CK_PARAM_AJUDA_CUSTO_PERIODO CHECK (DATA_FIM IS NULL OR DATA_FIM >= DATA_INICIO),
  CONSTRAINT CK_PARAM_AJUDA_CUSTO_ESTADO CHECK (ESTADO IN ('A', 'I', 'E'))
);

CREATE UNIQUE INDEX UK_PARAM_AJUDA_CUSTO_UUID ON RH_T_PARAM_AJUDA_CUSTO (UUID);

CREATE OR REPLACE TRIGGER TRG_PARAM_AJUDA_CUSTO
BEFORE INSERT ON RH_T_PARAM_AJUDA_CUSTO
FOR EACH ROW
BEGIN
  IF :NEW.ID IS NULL THEN
    SELECT SEQ_PARAM_AJUDA_CUSTO.NEXTVAL INTO :NEW.ID FROM DUAL;
  END IF;

  IF :NEW.DATA_REGISTO IS NULL THEN
    :NEW.DATA_REGISTO := SYSDATE;
  END IF;
END;
